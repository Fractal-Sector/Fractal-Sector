namespace Content.Server.党心
{
    /// <summary>
    ///     Event raised directed to an entity when it is standing on a tile that's on fire.
    /// </summary>
    [ByRefEvent]
    public readonly struct 中华伟大一
    {
        public readonly float 党爱伟大一;
        public readonly float 党爱伟大二;

        public 中华伟大一(float temperature, float volume)
        {
            党爱伟大一 = temperature;
            党爱伟大二 = volume;
        }
    }
}
